package aimemory

import (
	"bufio"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ArchiveAgents are the agents whose files `archive` may move.
var ArchiveAgents = []string{"claude", "codex", "qwen"}

// codexGenerated are rewritten by the next Codex consolidation, so moving them
// achieves nothing; their sources are what to move.
var codexGenerated = map[string]bool{"memory_summary.md": true, "MEMORY.md": true, "raw_memories.md": true}

// Move is one whole-file rename into the archive.
type Move struct {
	Agent     string   `json:"agent"`
	From      string   `json:"from"`
	To        string   `json:"to"`
	IndexRefs []string `json:"indexRefs"`
	base      string   // the archive directory To must stay inside
}

func (o Options) archiveRoots(agent string) []string {
	switch agent {
	case "claude":
		return o.claudeRoots()
	case "qwen":
		return append([]string{filepath.Join(o.qwenHome(), "memories")}, memoryDirs(filepath.Join(o.qwenHome(), "projects"))...)
	case "codex":
		return []string{o.codexRoot()}
	}
	return nil
}

// PlanArchive checks every path and returns the moves. It changes nothing.
func PlanArchive(o Options, agent string, paths []string) ([]Move, error) {
	roots := o.archiveRoots(agent)
	if roots == nil {
		return nil, fmt.Errorf("archive supports %s, not %q; name one of those agents", strings.Join(ArchiveAgents, ", "), agent)
	}
	var moves []Move
	seen := map[string]bool{}
	for _, p := range paths {
		m, err := planOne(agent, roots, p)
		if err != nil {
			return nil, err
		}
		if seen[m.From] {
			continue
		}
		seen[m.From] = true
		moves = append(moves, m)
	}
	return moves, nil
}

func planOne(agent string, roots []string, p string) (Move, error) {
	abs, err := filepath.Abs(p)
	if err != nil {
		return Move{}, fmt.Errorf("%s: %w; pass an absolute path", p, err)
	}
	info, err := os.Lstat(abs)
	if err != nil {
		return Move{}, fmt.Errorf("%s: %w; check the path with 'dot ai memory audit --agent %s'", p, err, agent)
	}
	if info.IsDir() {
		return Move{}, fmt.Errorf("%s: a directory; archive moves whole files only, so name the files inside it", p)
	}
	// The file's location (its parent resolved, the name kept) and, for a
	// symlink, what it points to must both lie inside one memory store.
	parent, err := filepath.EvalSymlinks(filepath.Dir(abs))
	if err != nil {
		return Move{}, fmt.Errorf("%s: its directory cannot be resolved (%w); check its permissions", p, err)
	}
	loc := filepath.Join(parent, filepath.Base(abs))
	target, err := filepath.EvalSymlinks(loc)
	if err != nil {
		return Move{}, fmt.Errorf("%s: a broken symlink (%w); remove it by hand or point it at a file inside the store", p, err)
	}
	for _, root := range roots {
		realRoot, err := filepath.EvalSymlinks(root)
		if err != nil {
			continue
		}
		rel, ok := within(realRoot, loc)
		if !ok {
			continue
		}
		if _, ok := within(realRoot, target); !ok {
			return Move{}, fmt.Errorf("%s: a symlink that resolves outside the %s memory store; dot moves only files inside it, so remove the link by hand if it is stale", p, agent)
		}
		var base, to string
		switch agent {
		case "codex":
			if codexGenerated[rel] || strings.HasPrefix(rel, "rollout_summaries/") {
				return Move{}, fmt.Errorf("%s: generated by Codex consolidation, which rewrites it; archive the source note instead", p)
			}
			base = filepath.Join(filepath.Dir(realRoot), "memories-archive")
		default:
			if rel == indexName {
				return Move{}, fmt.Errorf("%s: the store's index; dot never moves or edits it, so archive the files it links and remove their lines yourself", p)
			}
			if strings.HasPrefix(rel, archiveDir+"/") {
				return Move{}, fmt.Errorf("%s: already archived; to restore it, move it back with mv", p)
			}
			base = filepath.Join(realRoot, archiveDir)
		}
		to = filepath.Join(base, filepath.FromSlash(rel))
		if err := plainDirs(base, filepath.Dir(to)); err != nil {
			return Move{}, fmt.Errorf("%s: %w", p, err)
		}
		if _, err := os.Lstat(to); err == nil {
			return Move{}, fmt.Errorf("%s: %s already exists; rename or remove the archived copy first", p, to)
		}
		return Move{Agent: agent, From: loc, To: to, IndexRefs: indexRefs(agent, realRoot, rel), base: base}, nil
	}
	return Move{}, fmt.Errorf("%s: not inside a %s memory store; 'dot ai memory audit --agent %s' lists the store paths", p, agent, agent)
}

// plainDirs refuses a destination whose existing directories, from the archive
// base down to dir, include a symlink or a non-directory: a linked _archive or
// memories-archive could carry the move outside the place BOUNDARIES allows.
func plainDirs(base, dir string) error {
	rel, err := filepath.Rel(filepath.Dir(base), dir)
	if err != nil || strings.HasPrefix(rel, "..") {
		return fmt.Errorf("destination %s is outside %s", dir, base)
	}
	cur := filepath.Dir(base)
	for _, part := range strings.Split(rel, string(filepath.Separator)) {
		cur = filepath.Join(cur, part)
		info, err := os.Lstat(cur)
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return fmt.Errorf("destination %s cannot be checked (%w); check its permissions", cur, err)
		}
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("destination %s is a symlink or a file, not a directory; replace it with a plain directory and re-run", cur)
		}
	}
	return nil
}

// within returns path relative to root (slash-separated) when path lies below root.
func within(root, path string) (string, bool) {
	rel, err := filepath.Rel(root, path)
	if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", false
	}
	return filepath.ToSlash(rel), true
}

// indexRefs lists the index lines that still name the file, for the person (or
// the agent) to remove: dot does not edit agent-written indexes.
func indexRefs(agent, root, rel string) []string {
	needle := rel
	indexes := []string{indexName}
	if agent == "codex" {
		needle = strings.TrimSuffix(filepath.Base(rel), ".md")
		indexes = []string{indexName, "memory_summary.md"}
	}
	refs := []string{}
	for _, name := range indexes {
		f, err := os.Open(filepath.Join(root, name))
		if err != nil {
			continue
		}
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 64*1024), 4*1024*1024)
		for n := 1; sc.Scan(); n++ {
			if strings.Contains(sc.Text(), needle) {
				refs = append(refs, fmt.Sprintf("%s:%d: %s", filepath.Join(root, name), n, sc.Text()))
			}
		}
		f.Close()
	}
	return refs
}

// ApplyArchive renames each file into place. It stops at the first failure and
// returns the moves already made, so the caller can print their reverse.
func ApplyArchive(moves []Move) ([]Move, error) {
	var done []Move
	for _, m := range moves {
		if err := plainDirs(m.base, filepath.Dir(m.To)); err != nil {
			return done, err
		}
		if err := os.MkdirAll(filepath.Dir(m.To), 0o755); err != nil {
			return done, fmt.Errorf("create %s: %w; check the permissions of its parent", filepath.Dir(m.To), err)
		}
		if err := plainDirs(m.base, filepath.Dir(m.To)); err != nil {
			return done, err
		}
		if _, err := os.Lstat(m.To); err == nil {
			return done, fmt.Errorf("%s already exists; rename or remove the archived copy first", m.To)
		} else if !errors.Is(err, os.ErrNotExist) {
			return done, fmt.Errorf("check %s: %w; check its permissions", m.To, err)
		}
		if err := os.Rename(m.From, m.To); err != nil {
			return done, fmt.Errorf("move %s: %w; check the permissions of both directories", m.From, err)
		}
		done = append(done, m)
	}
	return done, nil
}

// ReverseCommand is a shell command that puts the moved files back.
func ReverseCommand(moves []Move) string {
	parts := make([]string, 0, len(moves))
	for _, m := range moves {
		parts = append(parts, "mv -n "+shellQuote(m.To)+" "+shellQuote(m.From))
	}
	return strings.Join(parts, " && ")
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }
